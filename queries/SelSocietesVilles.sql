SELECT DISTINCTROW
  TBLSOCIETES.SocNum,
  TBLSOCIETES.SocDateCre,
  TBLSOCIETES.SocDateMaj,
  TBLSOCIETES.SocSocTypNum,
  TBLSOCIETESTYPES.SocTypLibelle,
  TBLSOCIETES.SocSocGrpNum,
  TBLSOCIETESGROUPES.SocGrpLibelle,
  TBLSOCIETES.SocSocResNum,
  TBLSOCIETESRESEAUX.SocResLibelle,
  TBLSOCIETES.SocCode,
  TBLSOCIETES.SocActif,
  TBLSOCIETES.SocAdhIpe,
  TBLSOCIETES.SocAdhConcours,
  TBLSOCIETES.SocEnseigne,
  TBLSOCIETES.SocRaison,
  TBLSOCIETES.SocAdr,
  TBLVILLES.VilCodePostal AS SocVilCodePostal,
  TBLVILLES.VilNom AS SocVilNom,
  TBLSOCIETES.SocTel1Libelle,
  TBLSOCIETES.SocTel1,
  TBLSOCIETES.SocTel2Libelle,
  TBLSOCIETES.SocTel2,
  TBLSOCIETES.SocFax,
  TBLSOCIETES.SocNotes,
  TBLSOCIETES.SocWeb
FROM
  TBLVILLES
  RIGHT JOIN (
    TBLSOCIETESTYPES
    INNER JOIN (
      TBLSOCIETESRESEAUX
      RIGHT JOIN (
        TBLSOCIETESGROUPES
        RIGHT JOIN TBLSOCIETES ON TBLSOCIETESGROUPES.SocGrpNum = TBLSOCIETES.SocSocGrpNum
      ) ON TBLSOCIETESRESEAUX.SocResNum = TBLSOCIETES.SocSocResNum
    ) ON TBLSOCIETESTYPES.SocTypNum = TBLSOCIETES.SocSocTypNum
  ) ON TBLVILLES.VilNum = TBLSOCIETES.SocVilNum
ORDER BY
  TBLSOCIETES.SocCode;
