TRANSFORM
  First(
    TBLPERSONNELSSOCIETESQUESTIONNAIRESRESULTATS.PerSocQstResValeur
  ) AS PerSocQstResValeurValeur
SELECT
  TBLPERSONNELSSOCIETESQUESTIONNAIRES.PerSocQstNum,
  TBLPERSONNELSSOCIETESQUESTIONNAIRES.PerSocQstPerSocQstTypNum,
  TBLPERSONNELSSOCIETESQUESTIONNAIRES.PerSocQstPerSocNum,
  TBLPERSONNELSSOCIETESQUESTIONNAIRES.PerSocQstDateSaisie,
  TBLPERSONNELSSOCIETESQUESTIONNAIRES.PerSocQstNotes
FROM
  TBLPERSONNELSSOCIETESQUESTIONNAIRESTYPES
  INNER JOIN (
    TBLPERSONNELSSOCIETESQUESTIONNAIRESTYPESID
    INNER JOIN (
      TBLPERSONNELSSOCIETESQUESTIONNAIRESRESULTATS
      INNER JOIN TBLPERSONNELSSOCIETESQUESTIONNAIRES ON TBLPERSONNELSSOCIETESQUESTIONNAIRESRESULTATS.PerSocQstResPerSocNum = TBLPERSONNELSSOCIETESQUESTIONNAIRES.PerSocQstPerSocNum
    ) ON TBLPERSONNELSSOCIETESQUESTIONNAIRESTYPESID.PerSocQstTypIDNum = TBLPERSONNELSSOCIETESQUESTIONNAIRESRESULTATS.PerSocQstResPerSocQstTypIDNum
  ) ON (
    TBLPERSONNELSSOCIETESQUESTIONNAIRESTYPES.PerSocQstTypNum = TBLPERSONNELSSOCIETESQUESTIONNAIRESTYPESID.PerSocQstTypIDPerSocQstTypNum
  )
  AND (
    TBLPERSONNELSSOCIETESQUESTIONNAIRESTYPES.PerSocQstTypNum = TBLPERSONNELSSOCIETESQUESTIONNAIRES.PerSocQstPerSocQstTypNum
  )
WHERE
  (
    (
      (
        TBLPERSONNELSSOCIETESQUESTIONNAIRESTYPES.PerSocQstTypNum
      ) = 3
    )
  )
GROUP BY
  TBLPERSONNELSSOCIETESQUESTIONNAIRES.PerSocQstNum,
  TBLPERSONNELSSOCIETESQUESTIONNAIRES.PerSocQstPerSocQstTypNum,
  TBLPERSONNELSSOCIETESQUESTIONNAIRES.PerSocQstPerSocNum,
  TBLPERSONNELSSOCIETESQUESTIONNAIRES.PerSocQstDateSaisie,
  TBLPERSONNELSSOCIETESQUESTIONNAIRES.PerSocQstNotes,
  TBLPERSONNELSSOCIETESQUESTIONNAIRESTYPES.PerSocQstTypCode,
  TBLPERSONNELSSOCIETESQUESTIONNAIRESTYPES.PerSocQstTypLibelle,
  TBLPERSONNELSSOCIETESQUESTIONNAIRESTYPES.PerSocQstTypDateDebut,
  TBLPERSONNELSSOCIETESQUESTIONNAIRESTYPES.PerSocQstTypDateFin,
  TBLPERSONNELSSOCIETESQUESTIONNAIRESTYPES.PerSocQstTypNbResultat
PIVOT
  'PerSocQstResValeur' & [PerSocQstTypID] In (
    'PerSocQstResValeur1', 'PerSocQstResValeur2'
  );
