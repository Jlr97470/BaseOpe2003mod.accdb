TRANSFORM
  First(
    TBLPERSONNELSSOCIETESOPERATIONSRESULTATS.PerSocOpeResValeur
  ) AS PerSocOpeResValeurValeur
SELECT
  TBLPERSONNELSSOCIETESOPERATIONS.PerSocOpeNum,
  TBLPERSONNELSSOCIETESOPERATIONS.PerSocOpePerSocOpeTypNum,
  TBLPERSONNELSSOCIETESOPERATIONS.PerSocOpePerSocNum,
  TBLPERSONNELSSOCIETESOPERATIONS.PerSocOpeDateSaisie,
  TBLPERSONNELSSOCIETESOPERATIONS.PerSocOpeNotes
FROM
  TBLPERSONNELSSOCIETESOPERATIONSTYPES
  INNER JOIN (
    TBLPERSONNELSSOCIETESOPERATIONSTYPESID
    INNER JOIN (
      TBLPERSONNELSSOCIETESOPERATIONSRESULTATS
      INNER JOIN TBLPERSONNELSSOCIETESOPERATIONS ON TBLPERSONNELSSOCIETESOPERATIONSRESULTATS.PerSocOpeResPerSocNum = TBLPERSONNELSSOCIETESOPERATIONS.PerSocOpePerSocNum
    ) ON TBLPERSONNELSSOCIETESOPERATIONSTYPESID.PerSocOpeTypIDNum = TBLPERSONNELSSOCIETESOPERATIONSRESULTATS.PerSocOpeResPerSocOpeTypIDNum
  ) ON (
    TBLPERSONNELSSOCIETESOPERATIONSTYPES.PerSocOpeTypNum = TBLPERSONNELSSOCIETESOPERATIONSTYPESID.PerSocOpeTypIDPerSocOpeTypNum
  )
  AND (
    TBLPERSONNELSSOCIETESOPERATIONSTYPES.PerSocOpeTypNum = TBLPERSONNELSSOCIETESOPERATIONS.PerSocOpePerSocOpeTypNum
  )
WHERE
  (
    (
      (
        TBLPERSONNELSSOCIETESOPERATIONSTYPES.PerSocOpeTypNum
      ) = 1
    )
  )
GROUP BY
  TBLPERSONNELSSOCIETESOPERATIONS.PerSocOpeNum,
  TBLPERSONNELSSOCIETESOPERATIONS.PerSocOpePerSocOpeTypNum,
  TBLPERSONNELSSOCIETESOPERATIONS.PerSocOpePerSocNum,
  TBLPERSONNELSSOCIETESOPERATIONS.PerSocOpeDateSaisie,
  TBLPERSONNELSSOCIETESOPERATIONS.PerSocOpeNotes,
  TBLPERSONNELSSOCIETESOPERATIONSTYPES.PerSocOpeTypCode,
  TBLPERSONNELSSOCIETESOPERATIONSTYPES.PerSocOpeTypLibelle,
  TBLPERSONNELSSOCIETESOPERATIONSTYPES.PerSocOpeTypDateDebut,
  TBLPERSONNELSSOCIETESOPERATIONSTYPES.PerSocOpeTypDateFin,
  TBLPERSONNELSSOCIETESOPERATIONSTYPES.PerSocOpeTypNbResultat
PIVOT
  'PerSocOpeResValeur' & [PerSocOpeTypID] In (
    'PerSocOpeResValeur1', 'PerSocOpeResValeur2',
    'PerSocOpeResValeur3', 'PerSocOpeResValeur4'
  );
