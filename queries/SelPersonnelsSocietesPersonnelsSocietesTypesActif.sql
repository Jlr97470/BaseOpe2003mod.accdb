SELECT DISTINCTROW
  TBLPERSONNELSSOCIETES.PerSocNum,
  TBLPERSONNELS.PerNum,
  TBLPERSONNELS.PerCivCode,
  TBLPERSONNELS.PerNom,
  TBLPERSONNELS.PerPrenom,
  TBLPERSONNELSSOCIETES.PerSocPerSocTypCode,
  TBLPERSONNELSSOCIETESTYPES.PerSocTypLibelle,
  TBLPERSONNELSSOCIETES.PerSocActif,
  TBLPERSONNELSSOCIETES.PerSocAdherent,
  TBLSOCIETES.SocNum,
  TBLSOCIETES.SocCode,
  TBLSOCIETES.SocEnseigne,
  TBLSOCIETES.SocRaison,
  TBLSOCIETES.SocAdr,
  TBLVILLES_1.VilCodePostal AS SocVilCodePostal,
  TBLVILLES_1.VilNom AS SocVilNom
FROM
  (
    TBLVILLES AS TBLVILLES_1
    INNER JOIN TBLSOCIETES ON TBLVILLES_1.VilNum = TBLSOCIETES.SocVilNum
  )
  INNER JOIN (
    TBLPERSONNELS
    INNER JOIN (
      TBLPERSONNELSSOCIETESTYPES
      INNER JOIN TBLPERSONNELSSOCIETES ON TBLPERSONNELSSOCIETESTYPES.PerSocTypCode = TBLPERSONNELSSOCIETES.PerSocPerSocTypCode
    ) ON TBLPERSONNELS.PerNum = TBLPERSONNELSSOCIETES.PerSocPerNum
  ) ON TBLSOCIETES.SocNum = TBLPERSONNELSSOCIETES.PerSocSocNum
WHERE
  (
    (
      (
        TBLPERSONNELSSOCIETES.PerSocActif
      ) = True
    )
  )
ORDER BY
  TBLPERSONNELS.PerNum;
