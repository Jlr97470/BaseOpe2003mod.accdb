SELECT
  TBLPERSONNELSSOCIETES.*,
  TBLPERSONNELSSOCIETESOPERATIONS.*,
  TBLPERSONNELSSOCIETESOPERATIONSTYPES.*,
  TBLPERSONNELSSOCIETESOPERATIONSRESULTATS.*
FROM
  TBLPERSONNELSSOCIETESOPERATIONSTYPES
  INNER JOIN (
    TBLPERSONNELSSOCIETES
    INNER JOIN (
      TBLPERSONNELSSOCIETESOPERATIONSRESULTATS
      INNER JOIN TBLPERSONNELSSOCIETESOPERATIONS ON TBLPERSONNELSSOCIETESOPERATIONSRESULTATS.PerSocOpeResPerSocNum = TBLPERSONNELSSOCIETESOPERATIONS.PerSocOpePerSocNum
    ) ON (
      TBLPERSONNELSSOCIETES.PerSocNum = TBLPERSONNELSSOCIETESOPERATIONSRESULTATS.PerSocOpeResPerSocNum
    )
    AND (
      TBLPERSONNELSSOCIETES.PerSocNum = TBLPERSONNELSSOCIETESOPERATIONS.PerSocOpePerSocNum
    )
  ) ON TBLPERSONNELSSOCIETESOPERATIONSTYPES.PerSocOpeTypNum = TBLPERSONNELSSOCIETESOPERATIONS.PerSocOpePerSocOpeTypNum;
