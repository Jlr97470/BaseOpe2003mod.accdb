SELECT
  TBLPERSONNELSSOCIETES.*,
  TBLPERSONNELSSOCIETESQUESTIONNAIRES.*,
  TBLPERSONNELSSOCIETESQUESTIONNAIRESTYPESID.*
FROM
  TBLPERSONNELSSOCIETES
  INNER JOIN (
    TBLPERSONNELSSOCIETESQUESTIONNAIRESTYPESID
    INNER JOIN TBLPERSONNELSSOCIETESQUESTIONNAIRES ON TBLPERSONNELSSOCIETESQUESTIONNAIRESTYPESID.PerSocQstTypIDPerSocQstTypNum = TBLPERSONNELSSOCIETESQUESTIONNAIRES.PerSocQstPerSocQstTypNum
  ) ON TBLPERSONNELSSOCIETES.PerSocNum = TBLPERSONNELSSOCIETESQUESTIONNAIRES.PerSocQstPerSocNum;
