SELECT
  TBLPERSONNELSSOCIETES.*,
  TBLPERSONNELSSOCIETESQUESTIONNAIRES.*,
  TBLPERSONNELSSOCIETESQUESTIONNAIRESTYPES.*,
  TBLPERSONNELSSOCIETESQUESTIONNAIRESRESULTATS.*
FROM
  TBLPERSONNELSSOCIETESQUESTIONNAIRESTYPES
  INNER JOIN (
    TBLPERSONNELSSOCIETES
    INNER JOIN (
      TBLPERSONNELSSOCIETESQUESTIONNAIRESRESULTATS
      INNER JOIN TBLPERSONNELSSOCIETESQUESTIONNAIRES ON TBLPERSONNELSSOCIETESQUESTIONNAIRESRESULTATS.PerSocQstResPerSocNum = TBLPERSONNELSSOCIETESQUESTIONNAIRES.PerSocQstPerSocNum
    ) ON (
      TBLPERSONNELSSOCIETES.PerSocNum = TBLPERSONNELSSOCIETESQUESTIONNAIRES.PerSocQstPerSocNum
    )
    AND (
      TBLPERSONNELSSOCIETES.PerSocNum = TBLPERSONNELSSOCIETESQUESTIONNAIRESRESULTATS.PerSocQstResPerSocNum
    )
  ) ON TBLPERSONNELSSOCIETESQUESTIONNAIRESTYPES.PerSocQstTypNum = TBLPERSONNELSSOCIETESQUESTIONNAIRES.PerSocQstPerSocQstTypNum;
